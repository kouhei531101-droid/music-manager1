function renderVersionsPage() {
  var el = document.getElementById('ver-body');
  if (!el) return;
  el.innerHTML = '<p class="panel-desc">今のバージョン：<strong>' + escapeHtml(APP_VERSION) + '</strong></p>' +
    CHANGELOG.map(function (c) {
      return '<section class="panel changelog-item">' +
        '<div class="changelog-head"><span class="changelog-version">' + escapeHtml(c.version) + '</span>' +
        '<span class="changelog-date">' + escapeHtml(c.date) + '</span>' +
        '<span class="changelog-title">' + escapeHtml(c.title) + '</span></div>' +
        '<ul>' + c.items.map(function (i) { return '<li>' + escapeHtml(i) + '</li>'; }).join('') + '</ul></section>';
    }).join('');
}
